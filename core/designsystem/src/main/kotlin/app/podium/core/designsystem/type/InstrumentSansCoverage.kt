package app.podium.core.designsystem.type

/**
 * Code points covered by Instrument Sans (generated from the bundled font's cmap with fontTools).
 * Used to pick the family per string so words never mix two typefaces (ADR-010).
 */
internal object InstrumentSansCoverage {
    /** Inclusive [start, end] pairs, sorted. */
    private val ranges = intArrayOf(0x0020, 0x007E, 0x00A0, 0x00A3, 0x00A5, 0x00A5, 0x00A7, 0x00AB, 0x00AE, 0x00B0, 0x00B4, 0x00B4, 0x00B6, 0x00B8, 0x00BA, 0x00BB, 0x00BF, 0x0107, 0x010A, 0x0113, 0x0116, 0x011B, 0x011E, 0x0123, 0x0126, 0x0127, 0x012A, 0x012B, 0x012E, 0x0133, 0x0136, 0x0137, 0x0139, 0x013E, 0x0141, 0x0148, 0x014A, 0x014D, 0x0150, 0x015B, 0x015E, 0x0161, 0x0164, 0x0165, 0x016A, 0x017E, 0x01CD, 0x01CE, 0x0218, 0x021B, 0x0237, 0x0237, 0x02C6, 0x02C7, 0x02D8, 0x02DD, 0x0300, 0x0304, 0x0306, 0x0308, 0x030A, 0x030C, 0x0312, 0x0312, 0x0326, 0x0328, 0x1E80, 0x1E85, 0x1E9E, 0x1E9E, 0x1EF2, 0x1EF3, 0x2013, 0x2014, 0x2018, 0x201A, 0x201C, 0x201E, 0x2022, 0x2022, 0x2026, 0x2026, 0x2030, 0x2030, 0x2039, 0x203A, 0x20AC, 0x20AC, 0x2122, 0x2122, 0x2190, 0x2199, 0x2212, 0x2212)

    fun covers(codePoint: Int): Boolean {
        var lo = 0
        var hi = ranges.size / 2 - 1
        while (lo <= hi) {
            val mid = (lo + hi) ushr 1
            val start = ranges[mid * 2]
            val end = ranges[mid * 2 + 1]
            when {
                codePoint < start -> hi = mid - 1
                codePoint > end -> lo = mid + 1
                else -> return true
            }
        }
        return false
    }
}
