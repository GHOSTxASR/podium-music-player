/*
 * Code points covered by the display fonts (generated from each bundled font's cmap with fontTools,
 * 2026-10-06). Used, like InstrumentSansCoverage, to pick the family per string so a word never mixes
 * two typefaces (ADR-010): a string the display font can't set entirely falls back to Inter.
 */

/** Inclusive [start, end] code point pairs, sorted. */
internal class FontCoverage(private val ranges: IntArray) {
    fun covers(codePoint: Int): Boolean {
        var lo = 0
        var hi = ranges.size / 2 - 1
        while (lo <= hi) {
            val mid = (lo + hi) ushr 1
            when {
                codePoint < ranges[mid * 2] -> hi = mid - 1
                codePoint > ranges[mid * 2 + 1] -> lo = mid + 1
                else -> return true
            }
        }
        return false
    }
}

